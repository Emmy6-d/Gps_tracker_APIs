create table if not exists public.telemetry (
  id bigint generated by default as identity primary key,
  device_id text not null,
  schema_version integer not null default 1,
  firmware_version text,
  uptime_seconds bigint not null default 0,
  temperature_c double precision,
  temperature_source text,
  wifi_rssi smallint,
  free_heap_bytes bigint,
  recorded_at timestamptz not null default now(),
  gps jsonb not null default '{}'::jsonb,
  wifi_access_points jsonb not null default '[]'::jsonb,
  received_at timestamptz not null default now()
);

-- Safe migration for databases created before temperature source metadata was added.
alter table public.telemetry
  add column if not exists temperature_source text;

create index if not exists telemetry_device_recorded_idx
  on public.telemetry (device_id, recorded_at desc);

alter table public.telemetry enable row level security;
-- The backend uses the Supabase service-role key. Browser clients only use FastAPI.
-- RLS bypass does not replace PostgreSQL table privileges, so grant only the
-- operations required by this backend role.
grant select, insert on table public.telemetry to service_role;
grant usage, select on sequence public.telemetry_id_seq to service_role;
